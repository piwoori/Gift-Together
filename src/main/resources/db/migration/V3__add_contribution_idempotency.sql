CREATE TABLE contribution_idempotency (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    funding_id bigint NOT NULL REFERENCES fundings(id),
    idempotency_key varchar(128) NOT NULL,
    amount bigint NOT NULL,
    anonymous boolean NOT NULL,
    simulate_payment_failure boolean NOT NULL,
    contribution_id bigint NOT NULL REFERENCES contributions(id),
    contribution_status varchar(20) NOT NULL,
    current_amount bigint NOT NULL,
    remaining_amount bigint NOT NULL,
    funding_status varchar(20) NOT NULL,
    CONSTRAINT uk_contribution_idempotency_scope UNIQUE (user_id, funding_id, idempotency_key)
);
